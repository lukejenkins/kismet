# ── The one-pass chain on an UNCONFIGURED tree ──────────────────────────────
# A stale built binary does not imply a configured tree: the baseline builds
# live in build-baseline/ with no Makefile anywhere. A bare
# `make -C <dir> <target>` there falls through to make's built-in rules, prints
# "Nothing to be done", exits 0 and rebuilds nothing.

# Real prerequisites, so link_dependencies() derives the closure from this
# makefile (a rule with none falls back to a glob and carries no makefile).
_STANDALONE_MK = (
    "baseline:\n\t@echo REBUILT-baseline\n"
    "build-baseline/kismet_cap_cell_diag build-baseline/kismet_cap_cell_at: "
    "drv.c\n"
    "diag_logstream_dump: dls.c\n\t@echo REBUILT-logstream\n"
    ".PHONY: baseline diag_logstream_dump\n")


def _baseline_built_clone(tmp_path):
    """An unconfigured tree after `--build`: every driver built, no Makefile."""
    clone = tmp_path / "tree"
    for role in ("celldiag", "cellat"):
        subdir, _t, out = parity._STANDALONE_ESCAPE[role]
        (clone / subdir).mkdir(parents=True, exist_ok=True)
        (clone / subdir / "standalone.mk").write_text(_STANDALONE_MK)
        (clone / subdir / "drv.c").write_text("")
        (clone / subdir / "dls.c").write_text("")
        _exe(clone / subdir / out)
    logstream = _exe(clone / "capture_cell_diag" / "diag_logstream_dump")
    return [
        parity.Discovery("celldiag", "discovered", clone / "capture_cell_diag"
                         / "build-baseline" / "kismet_cap_cell_diag", ""),
        parity.Discovery("cellat", "discovered", clone / "capture_cell_at"
                         / "build-baseline" / "kismet_cap_cell_at", ""),
        parity.Discovery("logstream", "discovered", logstream, ""),
    ]


def test_the_convergent_chain_names_standalone_mk_on_an_unconfigured_tree(
        tmp_path):
    cmd = parity.convergent_rebuild_for(_baseline_built_clone(tmp_path))
    assert cmd is not None
    links = cmd.split(" && ")
    assert len(links) == 3, links
    for link in links:
        assert "-f standalone.mk" in link, link
        assert "build-baseline" not in link, (
            f"`make -C build-baseline` names no makefile: {link}")


def test_the_convergent_chain_agrees_with_each_per_driver_remedy(tmp_path):
    """One spelling for both remedies, so they cannot drift apart again."""
    found = _baseline_built_clone(tmp_path)
    cmd = parity.convergent_rebuild_for(found)
    for d in found:
        per_driver = parity.staleness(d.role, d.path).rebuild_cmd()
        assert per_driver in cmd.split(" && "), (d.role, per_driver, cmd)


@pytest.mark.skipif(__import__("shutil").which("make") is None,
                    reason="no make on this host")
def test_every_link_of_the_convergent_chain_actually_runs_a_rule(tmp_path):
    """The behavioural half: make itself must find a rule for every link.

    A link that resolves to no rule prints `Nothing to be done` and exits 0,
    which the string tests above cannot detect.
    """
    import subprocess
    cmd = parity.convergent_rebuild_for(_baseline_built_clone(tmp_path))
