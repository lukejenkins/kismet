        assert not bad, (
            f"{name} references libwebsockets outside #ifdef HAVE_LIBWEBSOCKETS "
            f"at {bad[:5]} -- the no-lws baseline (Linux without lws, every "
            f"Darwin parity run) can no longer compile")

