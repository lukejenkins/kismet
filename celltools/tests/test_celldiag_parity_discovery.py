def test_build_on_an_unconfigured_tree_takes_the_standalone_escape(tmp_path,
                                                                   monkeypatch):
    """On an unconfigured tree `--build` builds `-f standalone.mk baseline`
    for the capture roles -- but only where standalone.mk exists, so the
    guarantee "never invoke make where it cannot work" still holds for a tree
    without one (tested above)."""
    _clear_role_env(monkeypatch)
    clone = _unconfigured_clone(tmp_path, monkeypatch)
    (clone / "capture_cell_diag" / "standalone.mk").write_text("baseline:\n")
    calls = []

    def fake_build(clone_, target, subdir="capture_cell_diag", makefile=None):
        calls.append((target, subdir, makefile))
        _exe(clone_ / subdir / "build-baseline" / "kismet_cap_cell_diag")
        return True, ""

    monkeypatch.setattr(parity, "_build", fake_build)
    found = parity.discover("celldiag", allow_build=True)
    assert calls == [("baseline", "capture_cell_diag", "standalone.mk")]
    assert found.status == "built", found
    assert found.path.parent.name == "build-baseline"


def test_a_build_baseline_binary_takes_its_closure_from_the_parent_standalone_mk(
        tmp_path):
    """The narrow-to-empty direction. A build-baseline/ binary's closure must
    not be derived from build-baseline/ itself: there is no makefile there, so
    the glob fallback finds only the generated config.h and version.c, and a
    source edit would leave the binary reading "current"."""
    src = tmp_path / "capture_cell_diag"
    bdir = src / "build-baseline"
    bdir.mkdir(parents=True)
    (tmp_path / "fw.c").write_text("")
    (tmp_path / "fw.h").write_text("")
    for name in ("a.c", "a.h", "b.inc"):
        (src / name).write_text("")
    (bdir / "config.h").write_text("")
    (src / "standalone.mk").write_text(
        "BASELINE_DIR = build-baseline\n"
        "BASELINE_BIN = $(BASELINE_DIR)/kismet_cap_cell_diag\n"
        "SRCS = a.c\n"
        "$(BASELINE_BIN): guard $(BASELINE_DIR)/config.h $(SRCS) ../fw.c ../fw.h\n"
        "\tcc -o $@ $(SRCS)\n")
    binary = _exe(bdir / "kismet_cap_cell_diag")

    deps = parity.link_dependencies(binary)
    assert deps.mode == "derived", deps.note
    names = {p.name for p in deps.sources}
    assert {"a.c", "fw.c", "fw.h", "config.h"} <= names, names
    assert {"a.h", "b.inc"} <= names, \
        "no .d files in a one-shot build: the directory's headers must be added"
    assert deps.makefile == src / "standalone.mk"

    st = parity.Staleness("celldiag", binary, (), deps)
    assert st.rebuild_cmd() == f"make -C {src} -f standalone.mk baseline"


