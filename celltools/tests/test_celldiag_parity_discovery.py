def _run_config_rule(tmp_path, **mk_vars):
    """Render capture_cell_diag's baseline config.h into tmp_path via make."""
    import shutil
    import subprocess
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    if shutil.which("make") is None:
        pytest.skip("no make on this host")
    if (clone / "config.h").exists():
        pytest.skip("configured tree: the rule COPIES ../config.h, by design")
    out = tmp_path / "bdir"
    args = [f"BASELINE_DIR={out}", *(f"{k}={v}" for k, v in mk_vars.items())]
    run = subprocess.run(
        ["make", "-C", str(clone / "capture_cell_diag"), "-f", "standalone.mk",
         *args, "baseline-platform-guard", f"{out}/config.h"],
        capture_output=True, text=True, check=False)
    cfg = out / "config.h"
    return run, (cfg.read_text() if cfg.exists() else "")


