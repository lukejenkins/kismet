def test_a_standalone_build_path_exists_for_the_half_that_can_have_one():
    """A standalone build path exists for capture_cell_diag.

    Asserts the file takes NO autoconf input. ``Makefile.in`` exists in that
    directory and is NOT a standalone path -- it is rendered by the top-level
    ``config.status`` and its first line is ``include ../Makefile.inc``, itself
    generated by ``configure``. *"It already has a Makefile.in"* is exactly the
    reasoning this test exists to refuse.
    """
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    mk = clone / "capture_cell_diag" / "standalone.mk"
    assert mk.exists(), "capture_cell_diag/standalone.mk is missing"

    body = mk.read_text(errors="replace")

    # Comment lines are stripped first. The file's own header EXPLAINS why
    # Makefile.in's `include ../Makefile.inc` disqualifies it, so a naive
    # substring search over the whole text matches the explanation and reports
    # the opposite of the truth. Assert on what make will execute.
    code = "\n".join(
        line for line in body.splitlines() if not line.lstrip().startswith("#")
    )
    assert "include ../Makefile.inc" not in code, (
        "standalone.mk includes the configure-generated Makefile.inc, so it is "
        "not standalone at all"
    )
    assert "@" + "CC@" not in code, "standalone.mk carries an autoconf substitution"

    # It must build the parity driver and offer a check target, or it does not
    # reduce the "unverified here" surface.
    assert "diag_logstream_dump" in body
    assert "check:" in body

    # ...and it MUST build the helper as the Python-decode baseline.
    #
    # "Builds without ./configure" is the property this file exists for: no
    # rendered ../Makefile.inc, no generated ../config.h, no ../diagspec/ C++
    # closure. "Builds without libwebsockets" is a separate property, and also
    # holds because the framework's lws code is #ifdef'd.
    assert "$(BASELINE_BIN):" in code or "kismet_cap_cell_diag:" in code, (
        "standalone.mk no longer builds the helper. The Python-decode baseline "
        "must stay buildable on a tree that has never run ./configure -- that "
        "is the reference configuration all native-decode work is subordinate to"
    )
    assert "baseline:" in code, "standalone.mk lost its `baseline` target"

    # The baseline is the PYTHON-decode configuration: it must link no native
    # decode objects. A `.cpp` source reaching in from ../diagspec/ here would
    # make the target a second native build wearing the baseline's name, and
    # every guard downstream would still pass.
    #
    # Asserted on SOURCES, not on -I flags: include paths do not link
    # anything; compiled sources do.
    diagspec_srcs = [
        tok
        for tok in code.split()
        if tok.startswith("../diagspec/") and tok.endswith((".cpp", ".cc"))
    ]
    assert not diagspec_srcs, (
        "standalone.mk compiles native decode sources into the baseline: "
        f"{diagspec_srcs}. The baseline links ZERO native decode objects by "
        "definition -- with them it is a native build wearing the baseline's "
        "name, and every guard downstream still passes."
    )


def test_the_standalone_baseline_does_not_write_the_autoconf_output_path():
    """Two makefiles must not share one output path.

    If ``standalone.mk``'s ``BASELINE_BIN`` equals ``Makefile.in``'s
    ``MONITOR_BIN``, running the documented buildability check --

        make -C capture_cell_diag -f standalone.mk baseline

    -- inside a CONFIGURED tree silently replaces the autoconf-built helper with
    a differently-built one (different ``config.h`` resolution, different ``-I``
    order, different link line), and every consumer afterwards measures the
    wrong artifact.

    Every other guard passes on either binary: both builds exit 0, both are
    legitimately role ``baseline`` so ``check_binary_symbols.sh`` is green, and
    ``.native_mode`` reads ``baseline`` either way. The symptom surfaces as
    unrelated-looking failures in argument handling, nowhere near the build
    system. ``celltools/Makefile``'s ``replay-gate`` keeps the NATIVE=1/baseline
    pair apart for the same reason; this pins that standalone.mk keeps its
    output elsewhere too.
    """
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")

    d = clone / "capture_cell_diag"
    mk_in = d / "Makefile.in"
    mk_alone = d / "standalone.mk"
    if not (mk_in.exists() and mk_alone.exists()):
        pytest.skip("this tree has no capture_cell_diag build files")

    def _assign(text: str, var: str) -> str | None:
        """The single-line value of ``var = ...``, comments stripped."""
        for line in text.splitlines():
            if line.lstrip().startswith("#"):
                continue
            m = re.match(rf"{re.escape(var)}\s*[:?]?=\s*(.*)", line.strip())
            if m:
                return m.group(1).strip()
        return None

    monitor = _assign(mk_in.read_text(errors="replace"), "MONITOR_BIN")
    baseline = _assign(mk_alone.read_text(errors="replace"), "BASELINE_BIN")
    baseline_dir = _assign(mk_alone.read_text(errors="replace"), "BASELINE_DIR")

    assert monitor, "could not parse MONITOR_BIN out of Makefile.in"
    assert baseline, "could not parse BASELINE_BIN out of standalone.mk"
    assert baseline_dir, "could not parse BASELINE_DIR out of standalone.mk"

    assert baseline != monitor, (
        f"standalone.mk writes {baseline!r}, the SAME path Makefile.in's "
        f"MONITOR_BIN writes. In a configured tree the buildability check then "
        f"clobbers the deliverable, and no guard downstream can tell."
    )

    # ...and specifically it must land under the directory standalone.mk owns
    # outright -- anywhere else is a new shared path rather than a fixed one.
    assert baseline.startswith("$(BASELINE_DIR)/"), (
        f"BASELINE_BIN is {baseline!r}; it must live under $(BASELINE_DIR) "
        f"({baseline_dir!r}), which standalone.mk owns and .gitignore covers"
    )


def test_standalone_baseline_module_set_matches_the_autoconf_one():
    """The two module lists are a hand-maintained MIRROR, and mirrors drift.

    ``standalone.mk``'s ``BASELINE_CELLDIAG_SRCS`` and ``Makefile.in``'s
    ``MONITOR_OBJS`` name the same pure-C module set in two files. Nothing makes
    them agree, and a divergence is silent in the worst direction: the
    standalone baseline builds, links, and passes its symbol guard while missing
    a module the autoconf build has (``diag_logstream`` is the one the
    logstream parity check runs on).

    Both files already pin their own COUNT at link time. A count catches a drop;
    it does not catch a swap. This diffs the names.
    """
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")

    d = clone / "capture_cell_diag"
    mk_in = d / "Makefile.in"
    mk_alone = d / "standalone.mk"
    if not (mk_in.exists() and mk_alone.exists()):
        pytest.skip("this tree has no capture_cell_diag build files")

    def _block(text: str, var: str) -> set[str]:
        """The whitespace/backslash-continued value of `var = ...`."""
        out: list[str] = []
        collecting = False
        for line in text.splitlines():
            stripped = line.strip()
            if not collecting:
                if stripped.startswith(f"{var} ="):
                    collecting = True
                    stripped = stripped.split("=", 1)[1].strip()
                else:
                    continue
            more = stripped.endswith("\\")
            out.extend(stripped.rstrip("\\").split())
            if not more:
                break
        return {t for t in out if t.endswith((".c", ".c.o"))}

    autoconf = {n[: -len(".o")] if n.endswith(".c.o") else n
                for n in _block(mk_in.read_text(errors="replace"), "MONITOR_OBJS")}
    standalone = _block(mk_alone.read_text(errors="replace"), "BASELINE_CELLDIAG_SRCS")

    assert autoconf, "could not parse MONITOR_OBJS out of Makefile.in"
    assert standalone, "could not parse BASELINE_CELLDIAG_SRCS out of standalone.mk"
    assert autoconf == standalone, (
        "the standalone baseline and the autoconf baseline disagree on the "
        f"pure-C module set.\n"
        f"  only in Makefile.in:   {sorted(autoconf - standalone)}\n"
        f"  only in standalone.mk: {sorted(standalone - autoconf)}"
    )


