def _verdict(discoveries, rc=0, **counts):
    """Drive the verdict from (discovery, rc, what pytest ACTUALLY ran).

    Discovery state alone cannot tell "ran" from "skipped"; the counts can.
    Default per-harness counts mean "ran cleanly", so a test states only the
    harness it cares about.
    """
    import celldiag_parity_status as gauge  # noqa: E402
    resolved = {role: gauge.Counts(**counts.get(role, {"passed": 3}))
                for role in gauge.HARNESS}
    return gauge.verdict(discoveries, rc, resolved)


def _d(role, ok):
    return parity.Discovery(role, "discovered" if ok else "not-configured",
                            Path("/x") if ok else None, "")


_NOTHING = {"passed": 0, "skipped": 12, "reason": "no replay capture"}


def test_a_run_where_no_driver_existed_is_NOT_a_pass():
    """The gauge's own failure mode, form 1: no driver anywhere.

    On an unconfigured tree both harnesses skip and pytest exits 0. That must
    not render as PASS: "nothing complained" is not "the contract was checked".
    """
    line, ret = _verdict([_d("celldiag", False), _d("logstream", False)],
                         celldiag=_NOTHING, logstream=_NOTHING)
    assert "NO-OP" in line and "PASS" not in line
    assert "no harness had a driver" in line
    assert ret == 1, "an all-skipped run must not hand back success"


def test_drivers_present_but_every_test_skipped_is_NOT_a_pass():
    """The gauge's own failure mode, form 2: drivers built, nothing ran.

    Discovery answers "is there a driver?", but both harnesses also skip when
    the replay capture is absent (captures live outside git), which is the
    likelier miss. The verdict therefore keys on what pytest actually ran,
    which `--junitxml` reports per test, not on discovery state alone.
    """
    line, ret = _verdict([_d("celldiag", True), _d("logstream", True)],
                         celldiag=_NOTHING, logstream=_NOTHING)
    assert "NO-OP" in line and "PASS" not in line
    assert ret == 1
    # It must not blame an absent driver -- every driver was present. Naming the
    # wrong cause sends the operator to `--build`, which cannot help.
    assert "no harness had a driver" not in line
    assert "SKIPPED every test" in line and "no replay capture" in line, (
        "the verdict must carry pytest's own skip reason, or the operator "
        "cannot tell which silence this is")


def test_a_partial_run_says_which_half_is_unverified():
    line, ret = _verdict([_d("celldiag", True), _d("logstream", False)],
                         logstream=_NOTHING)
    assert "PARTIAL" in line and "logstream" in line
    assert ret == 0


def test_a_harness_that_half_skipped_is_PARTIAL_not_PASS():
    """Discovery says ran; the counts say half of it did not.

    A verdict keyed on discovery alone never sees a skip it did not predict.
    """
    line, ret = _verdict([_d("celldiag", True), _d("logstream", True)],
                         logstream={"passed": 2, "skipped": 2,
                                    "reason": "no NR fixture"})
    assert "PARTIAL" in line and "PASS" not in line
    assert "logstream" in line and "no NR fixture" in line
    assert ret == 0


def test_a_genuine_full_run_still_says_PASS():
    """The negative control for all of the above: don't cry wolf on a real pass."""
    line, ret = _verdict([_d("celldiag", True), _d("logstream", True)])
    assert line.startswith("PASS")
    assert "6 tests executed, 0 skipped" in line, (
        "PASS must state how much ran -- a bare PASS is what let both "
        "regressions hide")
    assert ret == 0


def test_a_real_failure_outranks_the_nothing_ran_verdict():
    """A nonzero pytest rc is a FAIL even if discovery looks incomplete --
    something ran and it broke; that is the more urgent fact."""
    line, ret = _verdict([_d("celldiag", True), _d("logstream", False)], rc=1)
    assert "FAIL" in line and "rc=1" in line
    assert ret == 1


def test_parse_junit_separates_passed_from_skipped(tmp_path):
    """The parse step itself, against a real pytest junit document.

    An all-skipped and an all-passed run are indistinguishable by exit code and
    plainly different here.
    """
    import celldiag_parity_status as gauge  # noqa: E402
    (tmp_path / "j.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?><testsuites><testsuite>'
        '<testcase classname="celltools.tests.test_celldiag_replay_ab" name="a"/>'
        '<testcase classname="celltools.tests.test_celldiag_replay_ab" name="b">'
        '<skipped message="no replay capture"/></testcase>'
        '<testcase classname="celltools.tests.test_celldiag_logstream_parity" name="c">'
        '<failure message="mismatch"/></testcase>'
        '</testsuite></testsuites>')
    counts = gauge.parse_junit(tmp_path / "j.xml")
    assert (counts["celldiag"].passed, counts["celldiag"].skipped) == (1, 1)
    assert counts["celldiag"].reason == "no replay capture"
    assert counts["logstream"].failed == 1
    assert not counts["celldiag"].executed, "a skip means it did not fully run"
    assert not counts["logstream"].executed


def test_a_missing_junit_report_is_not_read_as_success(tmp_path):
    """If the report never got written, the counts must be empty -- i.e. NO-OP.

    Failing open here would restore the original bug by a new route.
    """
    import celldiag_parity_status as gauge  # noqa: E402
    counts = gauge.parse_junit(tmp_path / "absent.xml")
    assert all(not c.executed for c in counts.values())


# ── A tree that CANNOT be configured is a host fact, not an omission ──
#
# On a host without libwebsockets, `./configure` hard-fails:
#
#     checking for libwebsockets >= 3.1.0... no
#     configure: error: Package requirements (libwebsockets >= 3.1.0) were not met
#
# The drivers under test do not use libwebsockets themselves; the contract is
# gated on a Kismet SERVER dependency only because the documented build path is
# the top-level autoconf configure. Telling the operator to run `./configure`
# there is a remedy that cannot work, i.e. a skip whose stated cause is wrong.

def test_a_tree_that_cannot_be_configured_is_its_own_status(tmp_path, monkeypatch):
    """`not-configured` (an omission) vs `not-configurable` (a host fact)."""
    for env_var, _, _ in parity.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    monkeypatch.delenv("CELLDIAG_PARITY_BUILD", raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setattr(parity, "missing_configure_deps",
                        lambda clone: ["libwebsockets"])

    found = parity.discover("celldiag", allow_build=True)
    assert found.status == "not-configurable", \
        f"a host missing a configure dep reported as {found.status!r}"
    assert not found.ok


def test_the_unconfigurable_remedy_names_the_package_not_configure(tmp_path,
                                                                   monkeypatch):
    """The remedy must NOT be `./configure`.

    Advising a command that hard-fails is worse than advising nothing: it reads
    as "you forgot a step" when the truth is "this machine cannot do it", and
    the operator burns a cycle discovering that."""
    for env_var, _, _ in parity.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setattr(parity, "missing_configure_deps",
                        lambda clone: ["libwebsockets"])

    reason = parity.discover("celldiag").skip_reason()
    assert "libwebsockets" in reason, "the missing module is not named"
    assert "libwebsockets-dev" in reason, "no installable package named"
    assert "run `cd" not in reason and "./configure`, then" not in reason, \
        f"the unconfigurable remedy still tells the operator to ./configure: {reason}"


def test_every_role_records_whether_it_has_a_standalone_build(tmp_path,
                                                              monkeypatch):
    """The two tables must PARTITION ``ROLES``.

    A role in neither leaves role-generic code reaching for a fact it does not
    have, and filling the gap with prose written about some other role. ``_standalone_note`` degrades to an explicit
    "unrecorded" rather than a wrong sentence, and this asserts we never ship
    that."""
    assert not (set(parity._STANDALONE_ESCAPE) &
                set(parity._NO_STANDALONE_ESCAPE)), \
        "a role cannot both have and not have a standalone build"
    assert set(parity._STANDALONE_ESCAPE) | set(parity._NO_STANDALONE_ESCAPE) \
        == set(parity.ROLES), "a role's standalone status is unrecorded"
    for role in parity.ROLES:
        assert "unrecorded" not in parity._standalone_note(role, tmp_path)


def test_the_standalone_advice_names_a_makefile_that_actually_exists():
    """The escape hatch must not point at a missing file.

    The standalone build is the one documented escape from a
    `not-configurable` host, so advice naming a ``standalone.mk`` that does not
    exist is a dead end that reads exactly like advice that works. Every
    ``-C <dir> -f standalone.mk`` this module can print is checked against the
    real tree."""
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    advised = set()
    for role in parity.ROLES:
        for m in re.finditer(r"-C (\S+) -f standalone\.mk",
                             parity._standalone_note(role, clone)):
            advised.add(Path(m.group(1)))
    assert advised, "no role advises a standalone build at all"
    for d in sorted(advised):
        assert (d / "standalone.mk").is_file(), \
            f"advised `make -C {d} -f standalone.mk` but {d}/standalone.mk is absent"


@pytest.mark.parametrize("role", sorted(parity.ROLES))
def test_the_standalone_advice_never_names_another_roles_binary(role):
    """The copy-paste tell, pinned per role.

    A note that names one role's binary while advising a build in another
    role's directory and offering a third role's override variable cannot be
    acted on. A reader must be able to use this text without first checking
    which driver it was written about, so no role's note may name another
    role's binary as the thing to build."""
    note = parity._standalone_note(role, parity.tree_root() or Path("/CLONE"))
    mine = Path(parity.ROLES[role][1]).name
    for other, (_, rel, _) in parity.ROLES.items():
        binary = Path(rel).name
        if other == role or binary == mine:
            continue
        assert f"build it{binary}" not in note, note
        # The `logstream` escape is deliberately cross-referenced from the roles
        # that have none -- as a NAMED OTHER role, never as this role's remedy.
        if binary in note:
            assert f"`{other}` role" in note or f"{other}-dump" in note, \
                f"{role}'s note names {binary} without saying whose it is: {note}"


def test_the_cellat_standalone_makefile_covers_every_lws_free_binary():
    """A selftest added to Makefile.in and not to standalone.mk goes MISSING.

    ``standalone.mk`` is a hand-maintained mirror of the framework-free recipes
    in ``Makefile.in`` -- it cannot include them, because Makefile.in's first
    line is ``include ../Makefile.inc``, itself generated by configure. That
    makes drift the obvious failure mode, and drift here is silent: the
    unconfigurable host simply never runs the new check. So the mirror is
    asserted rather than trusted.

    ``make check``'s prerequisite list in Makefile.in is the source of truth for
    "framework-free selftest", since anything needing the framework could not be
    a bare ``$(CC)`` recipe there either."""
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    d = clone / "capture_cell_at"
    template = (d / "Makefile.in").read_text()
    standalone = (d / "standalone.mk").read_text()

    binvars = dict(re.findall(r"^(\w+_BIN)\s*=\s*(\S+)\s*$", template, re.M))
    check = re.search(r"^check:((?:.*\\\n)*.*)$", template, re.M).group(1)
    expected = {binvars[v] for v in re.findall(r"\$\((\w+_BIN)\)", check)}
    assert expected, "could not resolve Makefile.in's `check` prerequisites"

    covered = set(re.findall(r"^\t(test_\w+)", standalone, re.M)) | \
        set(re.split(r"\s+", re.search(r"^TESTS\s*=\s*((?:.*\\\n)*.*)$",
                                       standalone, re.M).group(1)
                     .replace("\\\n", " ").strip()))
    missing = expected - covered
    assert not missing, \
        (f"capture_cell_at/standalone.mk does not build {sorted(missing)}, "
         f"which `make check` runs -- an unconfigurable host silently skips them")


def test_the_cellat_standalone_makefile_lists_and_defines_each_selftest_once():
    """A mirror fix applied twice is also drift.

    A selftest listed twice in ``TESTS`` with its recipe defined twice makes
    make only warn ("overriding recipe"), ``check`` then runs the test twice,
    and the coverage test above stays green, so duplicates are asserted here."""
    clone = parity.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    standalone = (clone / "capture_cell_at" / "standalone.mk").read_text()

    tests = re.split(r"\s+", re.search(r"^TESTS\s*=\s*((?:.*\\\n)*.*)$",
                                       standalone, re.M).group(1)
                     .replace("\\\n", " ").strip())
    listed_twice = sorted({t for t in tests if tests.count(t) > 1})
    assert not listed_twice, f"standalone.mk TESTS lists {listed_twice} more than once"

    targets = re.findall(r"^([\w$()]+):(?!=)", standalone, re.M)
    defined_twice = sorted({t for t in targets if targets.count(t) > 1})
    assert not defined_twice, f"standalone.mk defines {defined_twice} more than once"


