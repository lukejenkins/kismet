"""Generate ``diag_inventory_codes.h``: the log codes diaggrok has a parser for.

The native census (``diag_inventory.c``) needs one fact it cannot learn at run
time: whether a code that no native leg reads is one the reference decoder
DOES read. That splits "no decoder anywhere knows this" (``unrecognized``,
what diaggrok's own census would say) from "diaggrok decodes it and this
binary does not, yet" (``undecoded_native``, the native-coverage to-do list).

The answer is a fixed table committed as C, NOT derived at build time: a build
step that ran this would put Python and diaggrok back into the shipping build,
which is what a helper-less capture source exists to remove. Dev-only.
``tests/test_native_inventory_parity.py`` regenerates the table in memory and
fails when the committed file has drifted from the decoder in ``.deps``.

Regenerate, with the decoder library fetched and on the path::

    PYTHONPATH=.deps/diaggrok/src python3 fixtures/make_diaggrok_codes.py

It writes ``diag_inventory_codes.h`` in the directory above this one. Only
the shipped parsers count: diaggrok loads user plugins only when
``load_plugins()`` is called, which this never does.
"""
from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "diag_inventory_codes.h"
PER_LINE = 8


def render(codes: list[int]) -> str:
    rows = []
    for i in range(0, len(codes), PER_LINE):
        rows.append("    " + ", ".join(f"0x{c:04X}" for c in codes[i:i + PER_LINE])
                    + ",")
    return (
        "/* diag_inventory_codes.h - GENERATED by fixtures/make_diaggrok_codes.py.\n"
        " * Do not edit; regenerate. tests/test_native_inventory_parity.py fails\n"
        " * when this table drifts from the decoder in .deps.\n"
        " *\n"
        " * The log codes diaggrok registers a parser for (diaggrok.registered_codes()),\n"
        " * sorted, so the native census can tell `undecoded_native` (diaggrok reads\n"
        " * the code, no native leg does) from `unrecognized` (nothing reads it).\n"
        " * Included by diag_inventory.c only. */\n"
        f"/* {len(codes)} codes */\n"
        "#ifndef DIAG_INVENTORY_CODES_H\n"
        "#define DIAG_INVENTORY_CODES_H\n"
        "\n"
        "static const uint16_t DIAG_INVENTORY_DIAGGROK_CODES[] = {\n"
        + "\n".join(rows) + "\n"
        "};\n"
        "\n"
        "#endif\n")


def generate() -> str:
    import diaggrok
    codes = sorted({c for c in diaggrok.registered_codes() if 0 <= c <= 0xFFFF})
    return render(codes)


def main() -> int:
    OUT.write_text(generate())
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
